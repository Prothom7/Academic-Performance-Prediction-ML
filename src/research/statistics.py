def bootstrap_rho(x, y, replicates=1000):
    x, y = np.asarray(x), np.asarray(y)
    rng = np.random.default_rng(SEED)
    draws = []
    for _ in range(replicates):
        index = rng.integers(len(x), size=len(x))
        if np.unique(x[index]).size > 1 and np.unique(y[index]).size > 1:
            draws.append(spearmanr(x[index], y[index]).statistic)
    return np.quantile(draws, [.025, .975]).tolist() if draws else [np.nan, np.nan]

def characterization(raw):
    summaries, categories, numerics = [], [], []
    for col in raw:
        series = raw[col]
        kind = 'datetime metadata' if col == 'Timestamp' else ('numeric' if col == 'HSCGraduationYear' else ('ordered categorical' if col in ORDER_PREFIXES or col in ['Year1CGPA', 'Year2CGPA'] else 'nominal categorical'))
        summaries.append(dict(variable=col, human_readable_name=human_name(col), variable_type=kind,
            N=len(series), nonmissing_N=int(series.notna().sum()), missing_count=int(series.isna().sum()),
            missing_percent=100*series.isna().mean(), levels_or_range='; '.join(map(str, sorted(series.dropna().unique())))))
        if kind == 'numeric':
            descr = series.describe()
            numerics.append(dict(variable=col, N=int(descr['count']), missing_count=int(series.isna().sum()),
                mean=descr['mean'], standard_deviation=descr['std'], median=descr['50%'],
                q1=descr['25%'], q3=descr['75%'], minimum=descr['min'], maximum=descr['max']))
        else:
            for level, n in series.fillna('[Missing]').value_counts().sort_index().items():
                categories.append(dict(variable=col, category=level, count=n, percent_population=100*n/len(series),
                    percent_nonmissing=100*n/series.notna().sum() if level != '[Missing]' else np.nan))
    summary = save_table('dataset_summary', pd.DataFrame(summaries))
    save_table('categorical_distributions', pd.DataFrame(categories))
    save_table('numeric_distributions', pd.DataFrame(numerics))
    dictionary = '# Data dictionary\n\nGenerated by `src/research/statistics.py` from the authoritative full dataset. Original bilingual levels are retained in the CSV exports. CGPA and HSC scores are bands, not continuous measurements. No band midpoints are treated as observed values.\n\n' + summary.drop(columns='levels_or_range').to_markdown(index=False, floatfmt='.3f')
    dictionary += '\n\nSee [all category levels and counts](../results/tables/categorical_distributions.csv) and [numeric summaries](../results/tables/numeric_distributions.csv). Timestamp is administrative metadata and is excluded from all predictor sets.\n'
    (DOCS/'DATA_DICTIONARY.md').write_text(dictionary, encoding='utf-8')

def relationship(x, y):
    observed = pd.crosstab(x, y)
    if min(observed.shape) < 2:
        return dict(chi_square=np.nan, df=0, p_value=np.nan, cramers_v=np.nan,
            N=int(observed.to_numpy().sum()), minimum_expected=np.nan, fraction_expected_below_5=np.nan)
    statistic, p, dof, expected = chi2_contingency(observed, correction=False)
    n = int(observed.to_numpy().sum())
    return dict(chi_square=statistic, df=dof, p_value=p,
        cramers_v=np.sqrt(statistic/(n*(min(observed.shape)-1))), N=n,
        minimum_expected=expected.min(), fraction_expected_below_5=(expected < 5).mean())

def trajectories(df):
    matrix = pd.crosstab(df.Year1Band, df.Year2Band).reindex(index=range(5),columns=range(5),fill_value=0)
    save_table('transition_counts', matrix.rename_axis('Year1Band').reset_index().rename(columns={i:BANDS[i] for i in range(5)}))
    save_table('transition_row_percent', (matrix.div(matrix.sum(axis=1),axis=0)*100).rename_axis('Year1Band').reset_index().rename(columns={i:BANDS[i] for i in range(5)}))
    transitions = matrix.stack().rename('count').reset_index()
    transitions.columns = ['Year1Band', 'Year2Band', 'count']
    transitions['Year1Label'] = transitions.Year1Band.map(dict(enumerate(BANDS)))
    transitions['Year2Label'] = transitions.Year2Band.map(dict(enumerate(BANDS)))
    transitions['percent_population'] = 100*transitions['count']/len(df)
    save_table('year1_year2_alluvial', transitions)
    distribution = []
    for level in ['Declined', 'Stable', 'Improved']:
        n = int((df.Trajectory == level).sum())
        low, high = proportion_confint(n,len(df),method='wilson')
        distribution.append(dict(trajectory=level,count=n,N=len(df),percent=100*n/len(df),CI_low=100*low,CI_high=100*high))
    distribution = save_table('trajectory_distribution',pd.DataFrame(distribution))
    result = relationship(df.Year1Band, df.Year2Band)
    rho, p = spearmanr(df.Year1Band, df.Year2Band)
    low, high = bootstrap_rho(df.Year1Band, df.Year2Band)
    paired = wilcoxon(df.trajectory_delta, zero_method='wilcox', method='approx')
    moves = df.trajectory_delta[df.trajectory_delta != 0]
    sign_p = binomtest(int((moves>0).sum()),len(moves),p=.5).pvalue
    result.update(spearman_rho=rho,spearman_p=p,rho_CI_low=low,rho_CI_high=high,
        mean_band_change=df.trajectory_delta.mean(), signed_rank_statistic=paired.statistic,
        signed_rank_p=paired.pvalue, direction_sign_test_p=sign_p,
        note='Paired ordinal band change; mean change is in bands, not CGPA points.')
    save_table('persistence_statistics',pd.DataFrame([result]))
    subgroup = []
    for factor in ['Faculty','CurrentInstitution','Gender','CollegeCategory','LivingArrangement']:
        for level, group in df.groupby(factor,dropna=False):
            n = len(group)
            enough = n >= 20 and group.Year1Band.nunique()>1 and group.Year2Band.nunique()>1
            rho, p = spearmanr(group.Year1Band,group.Year2Band) if enough else (np.nan,np.nan)
            ci = bootstrap_rho(group.Year1Band,group.Year2Band,500) if enough else [np.nan,np.nan]
            subgroup.append(dict(factor=factor,subgroup=level,N=n,spearman_rho=rho,p_value=p,
                rho_CI_low=ci[0],rho_CI_high=ci[1],stable_percent=100*(group.Trajectory=='Stable').mean(),
                improved_percent=100*group.improved.mean(),declined_percent=100*group.declined.mean(),
                note='Correlation suppressed below N=20; contextual variation, no rankings.'))
    sub = pd.DataFrame(subgroup)
    sub['q_value'] = np.nan
    for _, indices in sub.groupby('factor').groups.items():
        valid = sub.loc[indices].p_value.dropna().index
        sub.loc[valid,'q_value'] = multipletests(sub.loc[valid,'p_value'],method='fdr_bh')[1]
    save_table('subgroup_persistence',sub)
    year_distribution = []
    for year in [1,2]:
        for band,n in df[f'Year{year}Band'].value_counts().sort_index().items():
            low,high = proportion_confint(n,len(df),method='wilson')
            year_distribution.append(dict(year=year,band=band,label=BANDS[band],count=n,N=len(df),
                percent=100*n/len(df),CI_low=100*low,CI_high=100*high))
    save_table('yearly_cgpa_distribution',pd.DataFrame(year_distribution))
    return result,distribution

def associations(df):
    predictors = [c for c in REQUIRED_COLUMNS if c not in ['Timestamp','Year1CGPA','Year2CGPA','ResearchParticipation']]+['Year1Band','Year2Band']
    rows, correlations = [], []
    for outcome in ['Year1Band','Year2Band','Trajectory','research']:
        for predictor in predictors:
            if predictor==outcome:
                continue
            usable = df[[predictor,outcome]].dropna()
            result = relationship(usable[predictor], usable[outcome])
            result.update(factor=predictor,outcome=outcome,analysis='unadjusted categorical association',
                input_dataset=relative(DATA),generating_script='src/research/statistics.py')
            rows.append(result)
            ordinal = predictor+'Ordinal' if predictor in ORDER_PREFIXES else predictor if predictor in ['HSCGraduationYear','Year1Band','Year2Band'] else None
            numeric_outcome = 'trajectory_delta' if outcome=='Trajectory' else outcome
            if ordinal:
                use = df[[ordinal,numeric_outcome]].dropna()
                rho,p = spearmanr(use[ordinal],use[numeric_outcome])
                ci = bootstrap_rho(use[ordinal],use[numeric_outcome],300)
                correlations.append(dict(factor=predictor,outcome=outcome,spearman_rho=rho,p_value=p,N=len(use),
                    CI_low=ci[0],CI_high=ci[1],note='Trajectory uses signed band change; ordinal trend assumes ordered spacing.'))
    master = pd.DataFrame(rows)
    corr = pd.DataFrame(correlations)
    for table in [master,corr]:
        table['q_value'] = table.groupby('outcome').p_value.transform(lambda p:multipletests(p,method='fdr_bh')[1])
    save_table('master_unadjusted_associations',master)
    save_table('spearman_associations',corr)
    return master

def descriptive_contrasts(df):
    rows = []
    specifications = [('HSCMath', ['high_year1','high_year2']),('HSCPhysics',['high_year1','high_year2']),
        ('HSCChemistry',['high_year1','high_year2']),('CollegeCategory',['high_year2','low_year2','research']),
        ('StudentClubMember',['research']),('DepartmentPreferenceOrder',['high_year2']),('Trajectory',['research']),
        ('Gender',['improved','declined']),('LivingArrangement',['improved','declined'])]
    for factor,outcomes in specifications:
        groups = df[factor].copy()
        if factor.startswith('HSC'):
            groups = np.where(df[factor+'Ordinal']==4,'190–200','All lower categories')
        for outcome in outcomes:
            temp = pd.DataFrame({'group':groups,'value':df[outcome]})
            for group,g in temp.groupby('group'):
                use = g.value.dropna()
                n,events = len(use),int(use.sum())
                low,high = proportion_confint(events,n,method='wilson')
                rows.append(dict(factor=factor,group=group,outcome=outcome,N=n,events=events,
                    percent=100*events/n,CI_low=100*low,CI_high=100*high))
    return save_table('descriptive_contrasts',pd.DataFrame(rows))
